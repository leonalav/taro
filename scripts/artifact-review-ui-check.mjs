import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { createServer } from 'vite';
import { chromium } from '../.verification-2026-11-08/browser-tools/node_modules/playwright/index.mjs';
const output='.verification-2026-11-10/artifact-design';await mkdir(output,{recursive:true});
const vite=await createServer({logLevel:'warn',server:{host:'127.0.0.1',port:1438,strictPort:true}});await vite.listen();
const browser=await chromium.launch({headless:true,channel:'msedge'}),context=await browser.newContext({viewport:{width:1600,height:1050}}),page=await context.newPage();page.setDefaultTimeout(30000);
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.route(/^https:\/\//,route=>route.abort());
await page.addInitScript(()=>{if(!localStorage.getItem('artifact-qa-seeded')){localStorage.setItem('artifact-qa-seeded','1');localStorage.setItem('taro-preferences-v1',JSON.stringify({appearance:{reduceMotion:true},account:{name:'Reviewer'}}));localStorage.setItem('taro-chat-v1',JSON.stringify({folders:[{id:'folder-artifact',name:'Artifact QA',path:'A:/artifact-qa'}],threads:[{id:'artifact-qa',name:'Artifact review',folderId:'folder-artifact',updated:'now',messages:[]}],activeThreadId:'artifact-qa'}));}});
const openReview=async()=>{const button=page.getByRole('button',{name:'Review mode — live design preview',exact:true});await button.waitFor();if(await button.getAttribute('aria-pressed')!=='true')await button.click();await page.getByRole('region',{name:'Review mode',exact:true}).waitFor();};
try{
  await page.goto('http://127.0.0.1:1438',{waitUntil:'domcontentloaded',timeout:120000});
  console.log('Loaded actual Taro UI');
  const identity=await page.evaluate(async()=>{
    const {executeArtifactTool}=await import('/src/lib/artifact-tools.ts');
    const context={workspace:'A:/artifact-qa',readOnly:false,planning:false};
    const initial=JSON.parse((await executeArtifactTool({action:'read',direction:'expressive'},context)).text);
    await executeArtifactTool({action:'save',design:initial.design,expected_revision:0},context);
    const same=JSON.parse((await executeArtifactTool({action:'read'},{...context,workspace:'a:\\artifact-qa\\'})).text);
    const other=JSON.parse((await executeArtifactTool({action:'read'},{...context,workspace:'A:/unrelated-qa'})).text);
    return {saved:same.saved,direction:same.design.direction,otherSaved:other.saved};
  });
  assert.deepEqual(identity,{saved:true,direction:'expressive',otherSaved:false});
  console.log('Verified actual project-memory storage and workspace isolation');
  await page.locator('.reception-recent').filter({hasText:'Artifact review'}).click();await openReview();
  const html=await readFile(`${output}/hero.html`,'utf8');
  await page.getByLabel('HTML artifact file').setInputFiles({name:'Editorial artifact.html',mimeType:'text/html',buffer:Buffer.from(html)});
  await page.getByRole('tab',{name:'Editorial artifact.html',exact:true}).waitFor();
  await page.getByRole('button',{name:'Show visual checks',exact:true}).click();
  await page.getByRole('button',{name:'Run visual checks',exact:true}).click();
  const panel=page.getByRole('complementary',{name:'Artifact visual checks',exact:true});
  await panel.getByRole('status').filter({hasText:'Manual review required'}).waitFor({timeout:60000});
  console.log('Completed audit through Review UI');
  assert.ok((await panel.getByRole('status').innerText()).includes('No failures in measured checks'));
  assert.equal(await panel.locator('.artifact-audit-case').count(),9);
  await panel.locator('.artifact-audit-case').first().locator('summary').first().click();
  await panel.getByRole('button',{name:'Open light desktop screenshot',exact:true}).click();
  const dialog=page.getByRole('dialog');await dialog.waitFor();
  await dialog.getByRole('button',{name:'Actual pixels',exact:true}).click();
  assert.equal(await dialog.locator('img').evaluate(img=>img.width===img.naturalWidth),true);
  await page.keyboard.press('Escape');await dialog.waitFor({state:'hidden'});
  await page.screenshot({path:`${output}/review-panel-wide.png`,fullPage:true});
  const persisted=await page.evaluate(async()=>{const request=indexedDB.open('taro-review-evidence-v1',1);const db=await new Promise((resolve,reject)=>{request.onsuccess=()=>resolve(request.result);request.onerror=()=>reject(request.error);});return await new Promise((resolve,reject)=>{const transaction=db.transaction('sessions','readonly'),query=transaction.objectStore('sessions').getAll();transaction.oncomplete=()=>resolve(query.result);transaction.onerror=()=>reject(transaction.error);});});
  assert.ok(persisted.some(raw=>JSON.parse(raw).previews.some(p=>p.revisions.some(r=>r.audits?.[0]?.cases.length===8))));
  await page.reload({waitUntil:'domcontentloaded'});
  const recent=page.locator('.reception-recent').filter({hasText:'Artifact review'});if(await recent.isVisible())await recent.click();
  await openReview();
  await page.getByRole('button',{name:'Show visual checks',exact:true}).click();
  await panel.getByRole('status').filter({hasText:'Manual review required'}).waitFor();
  await page.setViewportSize({width:850,height:900});
  await page.screenshot({path:`${output}/review-panel-narrow.png`,fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('PASS audit UI, eight saved cases, full-size screenshot dialog, IndexedDB persistence and reload, narrow layout; no page errors');
}finally{await context.close();await browser.close();await vite.close();}
